"""
Conformance tests for the BCMC peripheral model.

`bcmc_periph.py` is to `docs/Register_Map.md` what `reference.py` is to
`docs/BCMC.md`: an executable restatement of a specification. This script is
what makes that restatement trustworthy, and it follows the same three rules the
project has used since v0.2.

  1. **No invented answers.** Every matrix bit an expectation contains comes
     from `sim/vectors/matrix_*.txt`, generated by `reference.py`. The same
     files drive `sim/bcmc_row_test.cpp`, `sim/tb_column.v` and this suite, so
     agreement between them is agreement about one object, not three.

  2. **Only the register map.** The matrices compared here are built by writing
     and reading registers, exactly as `sw/bcmc.c` will. Nothing reaches inside
     the peripheral to fetch a value the bus does not expose.

  3. **The error model is re-derived, not shared.** `expected_errors()` below is
     an independent transcription of the E1-E4 table in the specification. It
     shares no code with `BcmcPeripheral._check_access`, so the two disagreeing
     is a real finding.

Run:
    python3 validation/test_periph.py
"""


# One case, through the register map alone
# ---------------------------------------------------------------------------

def check_vector_case(case, max_c, by_cell):
    """Return a list of failure messages (empty if the case passes)."""
    fails = []
    N, C = case["N"], case["C"]
    weights, expect_rows = case["weights"], case["rows"]

    dev = BcmcPeripheral(max_c=max_c)
    program(dev, N, weights)

    status = dev.read(REG_STATUS)
    if status & STATUS_BUSY:
        fails.append("BUSY still set after the polling loop returned")
    if not status & STATUS_VALID:
        fails.append("VALID not set after a completed transform")

    # --- the canonical representation, read back over the bus ---------------
    if read_offsets(dev, C) != case["offsets"]:
        fails.append("OFFSET window != the offsets in the vector file")

    for i in range(C):
        if dev.read(WEIGHT_BASE + 4 * i) != weights[i]:
            fails.append(f"WEIGHT[{i}] does not read back what was written")
            break

    # --- the matrix, through the COLUMN projection --------------------------
    rows = read_matrix(dev, N, C)
    if rows != expect_rows:
        fails.append("COLUMN projection != the matrix in the vector file")

    # --- the matrix, through CELL_ROW / CELL_COL / CELL ---------------------
    if by_cell and read_matrix(dev, N, C, by_cell=True) != expect_rows:
        fails.append("CELL projection != the matrix in the vector file")

    # --- the proved properties, re-established from bus reads only ----------
    for i in range(C):
        if sum(rows[i]) != weights[i]:
            fails.append(f"row conservation: row {i} popcount {sum(rows[i])} != {weights[i]}")
            break

    loads = [sum(rows[i][j] for i in range(C)) for j in range(N)]
    if loads != case["loads"]:
        fails.append("column occupancy != the L line in the vector file")

    W = sum(weights)
    q, r = divmod(W, N) if N else (0, 0)
    if loads != [q + 1] * r + [q] * (N - r):
        fails.append(f"Balance Theorem: W = {W} = {q}*{N} + {r} not honoured")

    # --- rows that do not exist are inactive lanes, not stale data ----------
    if C < max_c:
        dev.write(REG_CELL_ROW, C)
        for j in range(N):
            dev.write(REG_CELL_COL, j)
            if dev.read(REG_CELL) & 1:
                fails.append(f"row {C} >= C reads 1 at column {j}")
                break
        if dev.read(OFFSET_BASE + 4 * C) != 0:
            fails.append(f"OFFSET[{C}] was not cleared by the transform")

    return fails


# ---------------------------------------------------------------------------
# The error model, transcribed independently from docs/Register_Map.md
# ---------------------------------------------------------------------------

RO_REGS = (REG_ID, REG_VERSION, REG_CAPS, REG_CELL)
RW_REGS = (REG_CTRL, REG_STATUS, REG_N, REG_C, REG_CELL_ROW, REG_CELL_COL)


def expected_errors(dev, addr, write, sel=SEL_WORD, data=0):
    """
    Every reason the specification gives for refusing this access.

    A set, not a single reason, because the specification fixes *that* an
    access errs, not which condition is reported when several hold at once.
    Precedence is an implementation's business; refusal is the contract.
    """
    reasons = set()

    if addr < 0 or addr >= REGION_SIZE or addr % 4 != 0:
        reasons.add("E1")
        return reasons | ({"E3"} if sel != SEL_WORD else set())

    if sel != SEL_WORD:
        reasons.add("E3")

    in_weight = WEIGHT_BASE <= addr < WEIGHT_BASE + WINDOW_SPAN
    in_offset = OFFSET_BASE <= addr < OFFSET_BASE + WINDOW_SPAN
    in_column = COLUMN_BASE <= addr < COLUMN_LIMIT

    if addr in RO_REGS or addr in RW_REGS:
        if write and addr in RO_REGS:
            reasons.add("E2")
    elif in_column:
        if (addr - COLUMN_BASE) // 4 >= dev.column_words:
            reasons.add("E1")
        elif write:
            reasons.add("E2")
    elif in_weight:
        if (addr - WEIGHT_BASE) // 4 >= dev.max_c:
            reasons.add("E1")
    elif in_offset:
        if (addr - OFFSET_BASE) // 4 >= dev.max_c:
            reasons.add("E1")
        elif write:
            reasons.add("E2")
    else:
        reasons.add("E1")

    matrix_read = not write and (addr == REG_CELL or in_column or in_offset)
    context_write = write and (addr in (REG_N, REG_C) or in_weight)
    start_write = write and addr == REG_CTRL and bool(data & CTRL_START)

    # The two E4 rows overlap. Because START clears VALID before raising BUSY,
    # `BUSY` implies `!VALID`, so a matrix read while BUSY is refused twice
    # over and no bus master can tell which rule did it. The specification
    # states both anyway -- one is about a context being rewritten, the other
    # about a matrix not existing -- but a test cannot separate them, and this
    # comment is here so that nobody later mistakes that for a missing test.
    if dev.busy and (matrix_read or context_write or start_write):
        reasons.add("E4")
    if not dev.valid and matrix_read:
        reasons.add("E4")

    return reasons


def snapshot(dev):
    """Everything a write could legitimately change, and nothing else."""
    return (
        list(dev.weights), list(dev.offsets),
        dev.n, dev.c, dev.cell_row, dev.cell_col,
        dev.busy, dev.valid, dev.irq, dev.irq_en,
    )


def make_device(state, max_c=64):
    """A peripheral in one of the three states the E4 table distinguishes."""
    if state == "fresh":
        return BcmcPeripheral(max_c=max_c)
    if state == "valid":
        dev = BcmcPeripheral(max_c=max_c)
        program(dev, 8, [6, 3, 5])
        return dev
    if state == "busy":
        dev = BcmcPeripheral(max_c=max_c, latency=1_000_000)
        program(dev, 8, [6, 3, 5], poll=False)
        return dev
    raise ValueError(state)


def probe(dev, addr, write, sel=SEL_WORD, data=0):
    """Perform one access; return the reason it erred, or None."""
    try:
        if write:
            dev.write(addr, data, sel)
        else:
            dev.read(addr, sel)
    except BusError as exc:
        return exc.reason
    return None



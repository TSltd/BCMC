def load_matrix_vectors(path):
    """
    Parse one sim/vectors/matrix_*.txt file.

    The format is the one gen_vectors.py writes and sim/common/vectors.cpp
    reads:

        N <N> C <C>
        W <C weights>
        O <C offsets>
        R <bitstring>        one line per row; character 0 is column 0
        L <N occupancies>
    """
    cases = []
    cur = None
    with open(path) as handle:
        for lineno, raw in enumerate(handle, 1):
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            tok = line.split()
            tag = tok[0]
            if tag == "N":
                if len(tok) != 4 or tok[2] != "C":
                    raise ValueError(f"{path}:{lineno}: malformed header")
                cur = {"N": int(tok[1]), "C": int(tok[3]), "rows": []}
            elif cur is None:
                raise ValueError(f"{path}:{lineno}: '{tag}' outside a case")
            elif tag == "W":
                cur["weights"] = [int(t) for t in tok[1:]]
            elif tag == "O":
                cur["offsets"] = [int(t) for t in tok[1:]]
            elif tag == "R":
                cur["rows"].append([int(ch) for ch in tok[1]])
            elif tag == "L":
                cur["loads"] = [int(t) for t in tok[1:]]
                validate_case(cur, f"{path}:{lineno}")
                cases.append(cur)
                cur = None
            else:
                raise ValueError(f"{path}:{lineno}: unknown tag '{tag}'")
    if cur is not None:
        raise ValueError(f"{path}: last case has no L line")
    return cases


def validate_case(case, where):
    """The vector file must be internally well formed before it is believed."""
    N, C = case["N"], case["C"]
    if len(case["weights"]) != C or len(case["offsets"]) != C:
        raise ValueError(f"{where}: W/O length != C")
    if len(case["rows"]) != C:
        raise ValueError(f"{where}: {len(case['rows'])} R lines != C = {C}")
    if len(case["loads"]) != N:
        raise ValueError(f"{where}: L length != N")
    for row in case["rows"]:
        if len(row) != N:
            raise ValueError(f"{where}: row length != N")


